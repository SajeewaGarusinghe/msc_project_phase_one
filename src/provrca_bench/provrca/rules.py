"""The applicability table and the two rules, R1 and R2 (build guide P3 items 3-5).

**The table is data, not code** (``config/provrca/track-a.json``). A route is a method:
(caller, callee, method), as G0's route census (``11a-appendix-extras.md`` §A) and proposal §08
("routes that development data does not exercise are not on the allow-list") require. A route
that is not listed is *unknown* for both rules. The table is hashed (``Config.sha256``) so a run
can name exactly which table produced its verdicts.

**Each rule gives its own reason** for every matched pair, so RQ3 can measure reach per family
(F3 depends on R1, F2 on R2) instead of reading one merged code.

R1 (duration). Applies on a listed, unary route whose client span ends after the full response,
for an allowed role tier, when the client did not cancel or hit its deadline. Contradicted iff the
server span is longer than the client span plus ε.

R2 (status code). Compares the protocol code (``statusCode``; null is OK, K19), never span status.
Operationalising §08's condition "client code was returned by the server, not generated by the
client" from the two codes alone:

========================  =====================  ============================================
server                    client                 reason
========================  =====================  ============================================
any                       1 CANCELLED, 4         ``NA_STATUS_LOSSY`` client_cancelled /
                          DEADLINE_EXCEEDED      client_deadline (generated by the client)
equal                     equal                  ``OK_STATUS``
non-OK                    OK                     ``R2_STATUS_CONFLICT``: a client cannot
                                                 generate OK, so the server's claimed error
                                                 never reached its caller (the F2 shape)
OK                        other non-OK           ``NA_STATUS_LOSSY`` client_generated_possible
                                                 (transport/Envoy codes, K20; G0's three clean
                                                 disagreements are exactly this)
non-OK a                  non-OK b != a          ``NA_STATUS_LOSSY`` codes_differ_both_error
========================  =====================  ============================================

The client-generated row comes first. This supersedes two sentences of build guide P3 item 5
(client DEADLINE_EXCEEDED "compatible"; HTTP 4xx "compatible"): §08's condition and G0 step 6
put them out of the rule's reach (decisions log, 25 Nov, "P3 step 2").
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from provrca_bench.verdicts import Reason

DEFAULT_CONFIG = Path(__file__).resolve().parents[3] / "config" / "provrca" / "track-a.json"


@dataclass(frozen=True)
class Route:
    caller: str
    callee: str
    method: str
    protocol: str
    unary: bool
    client_span_ends_after_full_response: bool
    allowed_tiers: tuple[str, ...]
    r1: bool
    r2: bool


@dataclass(frozen=True)
class Config:
    epsilon_us: int
    null_status_is_ok: bool
    grpc_valid_codes: frozenset[int]
    grpc_client_generated: dict[int, str]
    tiers_never_allowed: frozenset[str]
    routes: dict[tuple[str, str, str], Route]
    sha256: str

    @classmethod
    def load(cls, path: str | Path = DEFAULT_CONFIG) -> "Config":
        raw = Path(path).read_bytes()
        d = json.loads(raw)
        routes = {}
        for r in d["routes"]:
            route = Route(caller=r["caller"], callee=r["callee"], method=r["method"],
                          protocol=r["protocol"], unary=bool(r["unary"]),
                          client_span_ends_after_full_response=bool(
                              r["client_span_ends_after_full_response"]),
                          allowed_tiers=tuple(r["allowed_tiers"]), r1=bool(r["r1"]),
                          r2=bool(r["r2"]))
            key = (route.caller, route.callee, route.method)
            if key in routes:
                raise ValueError(f"route listed twice: {key}")
            bad = set(route.allowed_tiers) & set(d["tiers_never_allowed"])
            if bad:
                raise ValueError(f"{key} allows a tier the table forbids: {bad}")
            routes[key] = route
        eps = d["epsilon_us"]
        if not isinstance(eps, int) or eps < 0:
            raise ValueError("epsilon_us must be a non-negative integer (timer resolution only)")
        return cls(epsilon_us=eps, null_status_is_ok=bool(d["null_status_is_ok"]),
                   grpc_valid_codes=frozenset(d["grpc_valid_codes"]),
                   grpc_client_generated={int(k): v for k, v in d["grpc_client_generated"].items()},
                   tiers_never_allowed=frozenset(d["tiers_never_allowed"]),
                   routes=routes, sha256=hashlib.sha256(raw).hexdigest())


def _codes(s: pd.Series, null_is_ok: bool) -> pd.Series:
    """statusCode as a float (NaN where absent or not a number; 0 where null means OK)."""
    v = pd.to_numeric(s.replace("", np.nan), errors="coerce")
    return v.fillna(0.0) if null_is_ok else v


def apply_rules(pairs: pd.DataFrame, cfg: Config) -> pd.DataFrame:
    """R1 and R2 on matched pairs.

    ``pairs`` needs: caller, callee, method, tier, server_us, client_us, server_code, client_code
    (codes and durations as strings or numbers). Returns r1_reason, r1_detail, r2_reason,
    r2_detail, aligned to ``pairs``' index.
    """
    n = len(pairs)
    idx = pairs.index
    keys = list(zip(pairs.caller, pairs.callee, pairs.method))
    route = [cfg.routes.get(k) for k in keys]
    listed = np.array([r is not None for r in route], dtype=bool)
    tier_ok = np.array([r is not None and t in r.allowed_tiers for r, t in zip(route, pairs.tier)],
                       dtype=bool)
    unary = np.array([r is not None and r.unary for r in route], dtype=bool)
    r1_on = np.array([r is not None and r.r1 and r.client_span_ends_after_full_response
                      for r in route], dtype=bool)
    r2_on = np.array([r is not None and r.r2 for r in route], dtype=bool)

    s_code = _codes(pairs.server_code.astype(object), cfg.null_status_is_ok).to_numpy()
    c_code = _codes(pairs.client_code.astype(object), cfg.null_status_is_ok).to_numpy()
    s_us = pd.to_numeric(pairs.server_us, errors="coerce").to_numpy(dtype=float)
    c_us = pd.to_numeric(pairs.client_us, errors="coerce").to_numpy(dtype=float)
    cancelled = np.isin(c_code, [k for k, v in cfg.grpc_client_generated.items()])
    gen_detail = np.array([cfg.grpc_client_generated.get(int(c), "") if not np.isnan(c) else ""
                           for c in c_code], dtype=object)
    valid = np.isin(s_code, list(cfg.grpc_valid_codes)) & np.isin(c_code, list(cfg.grpc_valid_codes))

    def decide(conds):
        reason = np.full(n, "", dtype=object)
        detail = np.full(n, "", dtype=object)
        done = np.zeros(n, dtype=bool)
        for mask, r, d in conds:
            m = np.asarray(mask, dtype=bool) & ~done
            reason[m] = r
            detail[m] = d[m] if isinstance(d, np.ndarray) else d
            done |= m
        assert done.all()
        return reason, detail

    common = [
        (~listed, Reason.NA_BOUNDARY.value, "route_not_listed"),
        (~tier_ok, Reason.NA_ROLE.value, "tier_not_allowed"),
        (~unary, Reason.NA_STREAMING.value, ""),
    ]
    r1_reason, r1_detail = decide(common[:1] + [common[1], common[2]] + [
        (~r1_on, Reason.NA_BOUNDARY.value, "route_boundary_unknown"),
        (cancelled, Reason.NA_BOUNDARY.value, gen_detail),
        (np.isnan(s_us) | np.isnan(c_us), Reason.NA_BOUNDARY.value, "duration_missing"),
        (s_us > c_us + cfg.epsilon_us, Reason.R1_ENCLOSURE_FAIL.value, ""),
        (np.ones(n, dtype=bool), Reason.OK_ENCLOSED.value, ""),
    ])
    r2_reason, r2_detail = decide([
        (~listed, Reason.NA_STATUS_LOSSY.value, "route_not_listed"),
        common[1], common[2],
        (~r2_on, Reason.NA_STATUS_LOSSY.value, "route_status_lossy"),
        (~valid, Reason.NA_STATUS_LOSSY.value, "code_out_of_range"),
        (cancelled, Reason.NA_STATUS_LOSSY.value, gen_detail),
        (s_code == c_code, Reason.OK_STATUS.value, ""),
        ((s_code != 0) & (c_code == 0), Reason.R2_STATUS_CONFLICT.value, ""),
        ((s_code == 0) & (c_code != 0), Reason.NA_STATUS_LOSSY.value, "client_generated_possible"),
        (np.ones(n, dtype=bool), Reason.NA_STATUS_LOSSY.value, "codes_differ_both_error"),
    ])
    return pd.DataFrame({"r1_reason": r1_reason, "r1_detail": r1_detail,
                         "r2_reason": r2_reason, "r2_detail": r2_detail}, index=idx)


_CONTRA = (Reason.R1_ENCLOSURE_FAIL.value, Reason.R2_STATUS_CONFLICT.value)


def combine(r1: pd.Series, r2: pd.Series, d1: pd.Series, d2: pd.Series) -> tuple[pd.Series, pd.Series]:
    """One reason per item: contradicted if either rule contradicts (R1 first); else compatible if
    either holds (OK_ENCLOSED first); else R1's unknown, then R2's. Both rules' own reasons are
    kept beside it in the verdict record."""
    reason = np.select(
        [r1.isin(_CONTRA), r2.isin(_CONTRA), r1 == Reason.OK_ENCLOSED.value,
         r2 == Reason.OK_STATUS.value],
        [r1, r2, r1, r2], default=r1)
    detail = np.where(reason == r1.to_numpy(), d1, d2)
    return pd.Series(reason, index=r1.index), pd.Series(detail, index=r1.index)
